// k6 load stage for ONE arm at ONE concurrency level.
//
// WHY k6 AND NOT THE PYTHON DRIVER
// --------------------------------
// The first driver here was asyncio + httpx on the host. Its own do-nothing
// ceiling measured ~244 rps and DEGRADED above 64 connections, while the service
// was already serving ~800 rps - so above about 8 connections the Python client,
// not the service, was the thing being measured. The G3 headroom guard is what
// caught it. k6 runs in Go, inside the compose network, so it neither pays the
// Windows host's loopback cost nor competes with the service for a GIL.
//
// The SAME seeded tenant sequence generated by benchlib/workload.py is replayed
// here, in order, for both arms - k6 only changes who is generating the load, not
// what the load is.
import http from 'k6/http';
import { check } from 'k6';
import { SharedArray } from 'k6/data';
import { Counter } from 'k6/metrics';

const seq = new SharedArray('seq', function () {
  return JSON.parse(open('/work/results/sequence.json'));
});

const cacheHit = new Counter('cache_hit');
const cacheMiss = new Counter('cache_miss');
const cacheOff = new Counter('cache_off');

export const options = {
  scenarios: {
    level: {
      executor: 'constant-vus',
      vus: Number(__ENV.VUS),
      duration: __ENV.DURATION || '8s',
      gracefulStop: '5s',
    },
  },
  // Uncounted warmup is done by a separate short k6 invocation before the
  // measured one, so neither arm pays a cold-connection penalty the other avoids.
  discardResponseBodies: false,
  summaryTrendStats: ['avg', 'min', 'med', 'p(95)', 'p(99)', 'max'],
};

export default function () {
  // OFFSET separates the WARMUP window from the MEASURED window.
  //
  // WHY THIS EXISTS - a real defect found by adversarial review, 2026-07-31.
  // The warmup and the measured run are separate `docker run` k6 processes, so
  // __VU and __ITER both restart at their initial values. With no offset the
  // measured run replayed the SAME index range the warmup had just requested,
  // which meant the cached arm entered measurement with those exact keys already
  // resident. The effect was visible and large: measured hit rate climbed
  // 0.9375 -> 0.9997 across the ladder. That is not steady state, it is the
  // warmup pre-loading the answer key.
  //
  // With OFFSET the measured window reads a DIFFERENT region of the same seeded
  // sequence. Because the sequence is drawn iid, that region is distributionally
  // identical - so genuinely hot tenants are still warm (they recur, exactly as in
  // production) while cold-tail keys genuinely miss. That is the honest steady
  // state the claim is about.
  //
  // 99991 (prime, coprime with the 200k sequence length) replaces 100003, whose
  // doubling collapsed all VU base offsets into two narrow windows.
  const i = (__VU * 99991 + __ITER * 7919 + Number(__ENV.OFFSET || 0)) % seq.length;
  const tid = seq[i];
  const res = http.get(`${__ENV.BASE}/config/${tid}`);
  const ok = check(res, { 'status 200': (r) => r.status === 200 });
  if (ok) {
    const c = res.headers['X-Cache'];
    if (c === 'hit') cacheHit.add(1);
    else if (c === 'miss') cacheMiss.add(1);
    else cacheOff.add(1);
  }
}
